// 生成粘贴到 Codex 对话中的考核提示词：由 Codex 对照 Vault 原文逐题考察，
// 采用 grill-me 流程（一次一题、语义判分、不给提示、答错讲解）。
export function buildCodexQuizPrompt({ projectTitle, level }) {
  const rubricLines = (level.rubric ?? [])
    .map((entry) => `- [${entry.points}分] ${entry.item}`)
    .join("\n");
  const sourceLine = level.source
    ? `事实源原文（请先完整阅读，以它为判分依据）：个人知识库/${level.source}`
    : "事实源：以关卡笔记与挑战描述为准。";
  return [
    `请扮演我的「${projectTitle}」学习考官，考核我对关卡「${level.title}」的掌握情况。`,
    "",
    sourceLine,
    "",
    "考核范围（关卡笔记）：",
    level.notes?.trim() || "（无）",
    "",
    "评分细则（用于掌握度打分）：",
    rubricLines || "（无）",
    "",
    "考核流程要求：",
    "1. 先阅读事实源原文，一次只向我提一个问题，等我回答后再出下一题。",
    "2. 问题聚焦机制、取舍与后果（为什么这样设计、不这样做会怎样），避免背诵名词定义式的琐碎题。",
    "3. 对照原文与评分细则给我的回答做语义判分，允许不同的表述方式，但不要放水。",
    "4. 我答错时，先指出错误，再对照原文讲解正确答案；我答对时简短确认即可。除非我主动请求，否则不要给提示。",
    "5. 覆盖评分细则的主要条目后（约 3-5 题），给出总评：掌握度评分（0-100）、每条细则的达成情况、仍需补强的点。",
    "6. 总评最后提醒我：把这份总评粘贴回学习闯关「提交验证」里归档，或在确认掌握后点击「手工自评掌握」。",
    "",
    "现在开始，请提出第一个问题。",
  ].join("\n");
}
